// 🃏 Makes the two card files the game uses:
//   public/js/card-art.js        the pictures for the cards and packs
//   src/shared/data/card-list.js the list of cards (names, packs, rarities)
//   npm run build:cards
//
// The cards are designed in experiments/cards-and-coins/prototype.html (real sprites from
// sprites.js, flags from flag-icons, simple scenery drawn for the cards). This copies them out,
// so a new card in the prototype only needs this script run again.
// (A brand new PACK also needs an entry in PACKS in src/shared/cards.js: `npm test` will remind you.)
//
// Two things it does to the art on the way:
//   - class names get an "rc-" prefix, so they can't clash with app.css (which has its own .pole).
//   - flags stay inside the card as data: pictures, never /f/ files, so a card can't be used
//     to match a country's name to a quiz flag's scrambled file name.

import fs from "node:fs";

const root = new URL("../", import.meta.url);
const source = new URL("experiments/cards-and-coins/prototype.html", root);
const target = new URL("public/js/card-art.js", root);
const listTarget = new URL("src/shared/data/card-list.js", root);

const html = fs.readFileSync(source, "utf8");
const line = html.match(/^const D = (.*);$/m);
if (!line) throw new Error("Can't find the art in prototype.html (a line starting `const D = `).");
const D = JSON.parse(line[1]);

const RENAME = { scene: "rc-scene", spr: "rc-spr", pole: "rc-pole", held: "rc-held", poster: "rc-poster" };
const prefixed = (art) => art.replace(/class="([^"]*)"/g, (_, names) =>
  `class="${names.split(/\s+/).map((n) => RENAME[n] || n).join(" ")}"`);

const known = new Set([...Object.keys(RENAME), "sprite"]);
for (const art of Object.values(D.ART)) {
  for (const [, names] of art.matchAll(/class="([^"]*)"/g)) {
    for (const n of names.split(/\s+/)) {
      if (!known.has(n) && !n.startsWith("rc-")) console.warn(`Unknown class "${n}" in the card art: add it to cards.css and to RENAME here.`);
    }
  }
}

const entries = (obj) => Object.entries(obj).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(prefixed(v))},`).join("\n");
const out = `// AUTO-GENERATED by scripts/build-card-art.mjs from experiments/cards-and-coins/prototype.html.
// Don't edit by hand: change the prototype's art and run \`npm run build:cards\`.
// It's big, so the game only loads this file when a card is about to be shown.
export const ART = {
${entries(D.ART)}
};
export const PACK_ART = {
${entries(D.PACK_ART)}
};
export const BACK = ${JSON.stringify(D.BACK)};
export const COIN = ${JSON.stringify(D.COIN)};
`;
fs.writeFileSync(target, out);

// The list has no pictures in it on purpose: it goes to every browser in /api/meta.
const rows = Object.entries(D.CARDS).map(([id, c]) => JSON.stringify({ id, pack: c.pack, name: c.name, rarity: c.rarity || null, ...(c.story ? { story: c.story } : {}) }));
fs.writeFileSync(listTarget, `// AUTO-GENERATED by scripts/build-card-art.mjs from experiments/cards-and-coins/prototype.html.
// Don't edit by hand: change the prototype and run \`npm run build:cards\`.
// rarity: null means that card's rarity hasn't been decided yet.
export const CARD_LIST = [
  ${rows.join(",\n  ")},
];
`);
console.log(`Wrote public/js/card-art.js: ${Object.keys(D.ART).length} cards, ${Object.keys(D.PACK_ART).length} packs, ${Math.round(out.length / 1024)} KB`);
