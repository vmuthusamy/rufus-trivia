// Draw all 50 states using Census boundaries distributed by us-atlas (ISC).
// npm run build:state-maps. Files have opaque names and no answer labels.
import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { feature } from 'topojson-client';
import { geoPath } from 'd3-geo';
import { US_STATES } from '../src/shared/data/us-states.js';
const topology=JSON.parse(fs.readFileSync(new URL('../node_modules/us-atlas/states-albers-10m.json',import.meta.url),'utf8'));
const features=feature(topology,topology.objects.states).features.filter(f=>US_STATES.some(s=>s.name===f.properties.name));
if(features.length!==50) throw new Error('Expected exactly 50 state geometries');
const path=geoPath().digits(1);
const base=features.map(f=>`<path d="${path(f)}"/>`).join('');
const dir=new URL('../public/u/',import.meta.url);fs.mkdirSync(dir,{recursive:true});
const maps={};
for(const s of US_STATES){
 const f=features.find(f=>f.properties.name===s.name);
 const tiny=path.area(f)<900;
 const [x,y]=path.centroid(f);
 const marker=tiny?`<circle cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" r="19" fill="none" stroke="#ffbb66" stroke-width="3"/>`:'';
 const svg=`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 975 610"><rect width="975" height="610" rx="20" fill="#132e49"/><g fill="#54768d" stroke="#a8c3d2" stroke-width="1.5">${base}</g><path d="${path(f)}" fill="#ff983c" stroke="#ffe0ac" stroke-width="2"/>${marker}</svg>`;
 const name=createHash('sha256').update('rufus-state:'+s.code).digest('hex').slice(0,10)+'.svg';
 fs.writeFileSync(new URL(name,dir),svg);maps[s.code]={img:'/u/'+name,tiny};
}
fs.writeFileSync(new URL('../src/shared/data/state-maps.js',import.meta.url),'// Generated by scripts/build-state-maps.mjs; do not edit by hand.\nexport const STATE_MAPS = '+JSON.stringify(maps,null,2)+';\n');
console.log('Built 50 US state maps.');
